#!/usr/bin/env node
// Builds the browser version into build/web/: the editor's own files, plus
// wb2-web.js, which bundles the game tools (tools/*.js) with browser
// stand-ins for Node's fs, path, zlib and Buffer (web/node/) and the glue in
// web/main.js; and the gallery page (gallery.html), with gallery-web.js
// (web/gallery-page.js). No game files are included: each visitor uses their
// own copy, which never leaves their browser.
// Usage: node tools/build-web.js [outDir]
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DEFAULT_OUT = path.join(ROOT, 'build', 'web');
const BUILTINS = { fs: 'web/node/fs.js', path: 'web/node/path.js', zlib: 'web/node/zlib.js', buffer: 'web/node/buffer.js' };
// Shipped with the editor, as in the repository: the two campaigns.
const SEED = (f) => /^levels\/(Brickwood|Brickton) .*\.txt$/.test(f) || f === 'campaign/campaign.json';

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

// Every module reachable from the entry, with its require() names resolved
// to module ids (paths relative to the repository).
function collect(entry) {
  const modules = new Map();
  const queue = [entry];
  while (queue.length) {
    const id = queue.shift();
    if (modules.has(id)) continue;
    const source = fs.readFileSync(path.join(ROOT, id), 'utf8').replace(/^#!.*\n/, '');
    const deps = {};
    for (const [, name] of source.matchAll(/require\(\s*'([^']+)'\s*\)/g)) {
      let target = BUILTINS[name];
      if (!target) {
        if (!name.startsWith('.')) throw new Error(`${id}: can't bundle require('${name}')`);
        target = rel(path.resolve(ROOT, path.dirname(id), name));
        if (!target.endsWith('.js')) target += '.js';
      }
      deps[name] = target;
      queue.push(target);
    }
    modules.set(id, { source, deps });
  }
  return modules;
}

// entry's start() is called with startArg.
function bundle(entry, startArg) {
  const modules = collect(entry);
  const defs = [...modules].map(([id, { source, deps }]) => `${JSON.stringify(id)}: [function (require, module, exports, __filename, __dirname) {\n${source}\n}, ${JSON.stringify(deps)}]`);
  return `// WorldBuilder 2 Level Editor, browser version. Generated by tools/build-web.js.
(function () {
'use strict';
const defs = {
${defs.join(',\n')}
};
const cache = {};
// The global Buffer that Node modules expect (modules may also require it).
let Buffer;
function load(id) {
  if (cache[id]) return cache[id].exports;
  const [fn, deps] = defs[id];
  const module = { exports: {} };
  cache[id] = module;
  const dir = id.includes('/') ? id.slice(0, id.lastIndexOf('/')) : '';
  const req = (name) => {
    if (!(name in deps)) throw new Error('module not bundled: ' + name);
    return load(deps[name]);
  };
  fn.call(module.exports, req, module, module.exports, '/wb2/' + id, '/wb2/' + dir);
  return module.exports;
}
Buffer = load(${JSON.stringify(BUILTINS.buffer)}).Buffer;
load(${JSON.stringify(entry)}).start(${JSON.stringify(startArg)});
})();
`;
}

function seedFiles() {
  const seed = {};
  for (const dir of ['levels', 'campaign']) {
    for (const name of fs.readdirSync(path.join(ROOT, dir))) {
      const f = `${dir}/${name}`;
      if (SEED(f)) seed[f] = fs.readFileSync(path.join(ROOT, f), 'latin1');
    }
  }
  return seed;
}

function build(OUT = DEFAULT_OUT) {
  // Only ever clear a folder that holds an earlier build (or nothing).
  if (fs.existsSync(OUT) && fs.readdirSync(OUT).length && !fs.existsSync(path.join(OUT, 'wb2-web.js'))) {
    throw new Error(`${OUT} is not empty and isn't an earlier build; choose another folder`);
  }
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  for (const name of fs.readdirSync(path.join(ROOT, 'editor'))) {
    if (name === 'setup.html') continue; // the local server's setup page
    fs.copyFileSync(path.join(ROOT, 'editor', name), path.join(OUT, name));
  }
  fs.copyFileSync(path.join(ROOT, 'web', 'web.css'), path.join(OUT, 'web.css'));
  // The gallery is the front page (index.html); the editor is editor.html.
  fs.renameSync(path.join(OUT, 'index.html'), path.join(OUT, 'editor.html'));
  const editorFile = path.join(OUT, 'editor.html');
  let html = fs.readFileSync(editorFile, 'utf8');
  const marker = '<script src="level.js"></script>';
  if (!html.includes(marker)) throw new Error('editor/index.html: level.js script tag not found');
  html = html
    .replace('<link rel="stylesheet" href="style.css">', '<link rel="stylesheet" href="style.css">\n  <link rel="stylesheet" href="web.css">')
    .replace(marker, `<script src="wb2-web.js"></script>\n  ${marker}`);
  fs.writeFileSync(editorFile, html);
  fs.writeFileSync(path.join(OUT, 'wb2-web.js'), bundle('web/main.js', seedFiles()));
  fs.copyFileSync(path.join(ROOT, 'web', 'gallery.html'), path.join(OUT, 'index.html'));
  fs.writeFileSync(path.join(OUT, 'gallery-web.js'), bundle('web/gallery-page.js', null));
  // Links shared before the gallery became the front page.
  fs.writeFileSync(path.join(OUT, 'gallery.html'), '<!doctype html><meta charset="utf-8"><title>WorldBuilder 2 Gallery</title>'
    + '<script>location.replace("./" + location.hash)</script><a href="./">WorldBuilder 2 Gallery</a>\n');
  fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
  // Browsers keep files for a while (GitHub Pages: 10 minutes); a fingerprint
  // of each script and stylesheet in its URL makes them fetch new versions
  // straight away, so a page never mixes old and new files.
  for (const page of ['index.html', 'editor.html']) {
    const file = path.join(OUT, page);
    const html = fs.readFileSync(file, 'utf8').replace(/(src|href)="([\w-]+\.(?:js|css))"/g, (m, attr, name) => {
      const asset = path.join(OUT, name);
      if (!fs.existsSync(asset)) return m;
      const hash = require('crypto').createHash('sha256').update(fs.readFileSync(asset)).digest('hex').slice(0, 10);
      return `${attr}="${name}?v=${hash}"`;
    });
    fs.writeFileSync(file, html);
  }
  return OUT;
}

module.exports = { build, bundle, collect };

if (require.main === module) {
  const out = build(path.resolve(process.argv[2] || DEFAULT_OUT));
  const files = fs.readdirSync(out);
  console.log(`Wrote ${files.length} files to ${rel(out) || out}: ${files.join(', ')}`);
}
